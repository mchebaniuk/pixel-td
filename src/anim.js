// Простая «кукольная» анимация: спрайт режется на части (ноги, тело, крылья),
// и каждая часть двигается отдельно. Доли [x0, y0, x1, y1] даны для персонажа, смотрящего вправо.

// шаг: ноги по очереди поднимаются и выносятся вперёд-назад (rig-координаты — персонаж смотрит вправо)
const stride = (LEG, split, s, lift, swing) => [
  { r: [0, LEG, split, 1], sy: 1 - lift * Math.max(0, s), pivot: 'top', dx: -s * swing },     // задняя нога
  { r: [split, LEG, 1, 1], sy: 1 - lift * Math.max(0, -s), pivot: 'top', dx: s * swing },     // передняя нога
];

// враги: phase растёт с пройденным путём
export function enemyRig(type, phase, moving) {
  const s = moving ? Math.sin(phase) : 0;
  const bob = -Math.abs(s);
  switch (type) {
    case 'gargoyle': {
      // крылья поворачиваются в плечах: вверх — широкий замах, вниз — сильный гребок; ноги поджаты и болтаются
      const glide = 0.4 + 0.6 * Math.min(1, Math.max(0, 0.5 + Math.sin(phase * 0.35) * 1.5));
      const w = Math.sin(phase * 2.2) * glide;                // +1 — крылья вверху, −1 — внизу
      const lag = Math.sin(phase * 2.2 - 1.2) * glide;
      const ang = 0.55 * w;                                    // угол взмаха
      const persp = 1 - 0.25 * Math.max(0, -w);                 // крыло в нижней точке видно короче
      return { o: { dy: lag * 1.8 - 1, rot: 0.06 }, parts: [
        { r: [0.3, 0.5, 0.7, 1], dx: -lag * 0.6, dy: lag * 0.4 },                                    // ноги и хвост
        { r: [0, 0, 0.42, 0.6], rot: ang, at: [0.4, 0.42], sy: persp, pivot: 'bottom' },             // заднее крыло
        { r: [0.3, 0, 0.7, 0.62] },                                                                  // голова и торс
        { r: [0, 0.5, 0.3, 1] }, { r: [0.7, 0.5, 1, 1] },
        { r: [0.6, 0, 1, 0.6], rot: -ang, at: [0.6, 0.42], sy: persp, pivot: 'bottom' },             // переднее крыло
      ] };
    }
    case 'wolf': { // галоп: задние и передние лапы работают парами со сдвигом, корпус качается вперёд-назад
      const f = moving ? Math.sin(phase + 1.4) : 0;
      return { o: { rot: s * 0.07, dy: bob * 1.6 }, parts: [
        { r: [0, 0.66, 0.5, 1], sy: 1 - 0.4 * Math.max(0, s), pivot: 'top', dx: -s * 1.8 },          // задние лапы
        { r: [0.5, 0.66, 1, 1], sy: 1 - 0.4 * Math.max(0, f), pivot: 'top', dx: f * 1.8 },           // передние лапы
        { r: [0.22, 0.34, 0.72, 0.7], dy: Math.abs(f) * 0.5 },                                       // корпус
        { r: [0.22, 0, 0.72, 0.34], dy: Math.abs(f) * 0.5 - s * 0.7 },                               // всадник подпрыгивает в седле
        { r: [0, 0, 0.22, 0.7], rot: Math.sin(phase * 2) * 0.25, at: [0.2, 0.52] },                  // хвост виляет
        { r: [0.72, 0, 1, 0.7], dy: Math.abs(f) * 0.5 + f * 0.6, rot: -f * 0.06, at: [0.74, 0.45] }, // голова кивает
      ] };
    }
    case 'troll': { // тяжёлый шаг: ноги по очереди выносятся вперёд, длинные руки раскачиваются, тело переваливается
      const sink = Math.abs(s) * 0.7;
      return { o: { dy: bob * 1.1, rot: s * 0.045 }, parts: [
        { r: [0.08, 0.74, 0.48, 1], sy: 1 - 0.42 * Math.max(0, s), pivot: 'top', dx: -s * 1.8 },  // задняя нога
        { r: [0.48, 0.74, 0.86, 1], sy: 1 - 0.42 * Math.max(0, -s), pivot: 'top', dx: s * 1.8 },  // передняя нога
        { r: [0.86, 0.74, 1, 1], dy: sink, rot: -s * 0.22, at: [0.84, 0.33] },  // кулак ниже пояса — с рукой
        { r: [0, 0.74, 0.08, 1] },
        { r: [0, 0, 1, 0.3], dy: sink },                                        // голова и плечи
        { r: [0.2, 0.3, 0.82, 0.76], dy: sink },                                // туловище
        { r: [0, 0.3, 0.2, 0.76], dy: sink, rot: s * 0.22, at: [0.18, 0.33] },  // дальняя рука
        { r: [0.82, 0.3, 1, 0.76], dy: sink, rot: -s * 0.22, at: [0.84, 0.33] }, // ближняя рука
      ] };
    }
    case 'orc': { // латник: тяжёлый шаг, руки в латах качаются, корпус проседает
      const sink = Math.abs(s) * 0.5;
      return { o: { dy: bob * 0.9, rot: s * 0.04 }, parts: [
        ...stride(0.64, 0.5, s, 0.36, 1.3),
        { r: [0, 0, 1, 0.25], dy: sink },                                       // голова
        { r: [0.25, 0.25, 0.78, 0.68], dy: sink, dx: s * 0.3 },                 // кираса
        { r: [0, 0.25, 0.25, 0.64], dy: sink, rot: s * 0.25, at: [0.22, 0.3] },  // дальняя рука
        { r: [0.78, 0.25, 1, 0.64], dy: sink, rot: -s * 0.25, at: [0.8, 0.3] },  // ближняя рука
      ] };
    }
    case 'goblin': { // семенит, наклонившись вперёд; рука с ножом и свободная рука машут
      const hop = -Math.abs(s) * 0.3;
      return { o: { dy: bob * 1.2, rot: 0.06 + s * 0.05 }, parts: [
        ...stride(0.64, 0.5, s, 0.42, 1.2),
        { r: [0, 0, 1, 0.38], dy: hop, dx: s * 0.3 },                           // голова и уши
        { r: [0.3, 0.38, 0.75, 0.68], dx: s * 0.5, dy: hop },                   // туловище
        { r: [0, 0.38, 0.3, 0.64], dy: hop, rot: s * 0.3, at: [0.3, 0.42] },     // рука с ножом
        { r: [0.75, 0.38, 1, 0.64], dy: hop, rot: -s * 0.3, at: [0.75, 0.42] },  // свободная рука
      ] };
    }
    default: // скелет: дёрганый шаг, рука и меч болтаются, череп качается в противофазе
      return { o: { dy: bob * 0.8, rot: s * 0.06 }, parts: [
        ...stride(0.64, 0.5, s, 0.4, 1.3),
        { r: [0.3, 0.3, 0.62, 0.66], dx: s * 0.5 },                              // рёбра и таз
        { r: [0, 0.25, 0.3, 0.66], dx: s * 0.5, rot: s * 0.3, at: [0.27, 0.3] },  // рука
        { r: [0.62, 0.3, 1, 0.64], dx: s * 0.5, rot: -s * 0.2, at: [0.62, 0.34] }, // рука с мечом
        { r: [0, 0, 1, 0.3], dx: -s * 0.4, dy: Math.abs(s) * 0.3 },              // череп
      ] };
  }
}

const ease = k => k * k * (3 - 2 * k); // плавный разгон и торможение

// защитники на башнях: t — время, atk — 1→0 сразу после выстрела, windup — 0→1 перед выстрелом
export function unitRig(unit, t, atk, windup, seed) {
  const breath = Math.sin(t * 2.2 + seed);
  switch (unit) {
    case 'archer': { // натягивает тетиву, отклоняясь назад, после выстрела — отдача и возврат
      const pull = ease(windup), kick = atk * atk;
      return { o: { dx: -0.9 * pull + 1.4 * kick, rot: -0.05 * pull + 0.04 * kick + Math.sin(t * 1.3 + seed) * 0.015 * (1 - pull) }, parts: [
        { r: [0, 0.73, 1, 1], dx: 0.5 * pull - 0.6 * kick },  // ноги упираются
        { r: [0, 0, 1, 0.75], dy: breath * 0.35 - 0.4 * kick }, // корпус вместе с луком целиком
      ] };
    }
    case 'cyclops': { // поднимает валун над головой настоящими руками с картинки и швыряет его корпусом
      const up = ease(windup), hit = atk;
      // угол рук от плеча: 0 — как на картинке, −2.7 — подняты над головой (через перёд); на броске идут вперёд и вниз
      const arm = -2.7 * Math.max(up, hit * hit * 0.9);
      const bodyDy = breath * 0.45 + 1.2 * up - 0.8 * hit;
      const near = { r: [0, 0.16, 0.24, 0.64], rot: arm, at: [0.17, 0.24], dy: bodyDy };          // ближняя рука
      const far = { r: [0.76, 0.16, 1, 0.64], rot: arm * 1.06, at: [0.83, 0.24], dy: bodyDy };   // дальняя рука
      return { o: { rot: -0.12 * up + 0.22 * hit + Math.sin(t * 0.9 + seed) * 0.02, dx: -0.8 * up + 2 * hit }, parts: [
        far, near,                                                   // обе руки за туловищем: торс закрывает место крепления
        { r: [0, 0.62, 1, 1], sy: 1 - 0.06 * up, pivot: 'top' },     // ноги приседают на замахе
        { r: [0.2, 0, 0.8, 0.64], dy: bodyDy },                      // голова и торс
      ], arms: { near, far } };
    }
    case 'lich': { // жрец поднимает посох перед лучом и вскидывает его при выстреле; подол колышется
      const lift = 1.2 * ease(windup) + 1.6 * atk;
      return { o: {}, parts: [
        { r: [0, 0.74, 0.72, 1], dx: Math.sin(t * 2.2 + seed) * 0.35 },            // подол мантии
        { r: [0, 0, 0.72, 0.75], dy: breath * 0.3 },                                // тело
        { r: [0.72, 0, 1, 1], dy: -lift + breath * 0.2 },                           // рука с посохом
      ] };
    }
    case 'dragon': { // крылья машут; при выдохе голова выбрасывается вперёд, крылья распахиваются; хвост качается
      const fire = Math.min(1, atk * 1.6);
      const flap = (0.5 + 0.5 * Math.sin(t * 5 + seed)) * (1 - fire) + fire * 0.05;
      const tail = Math.sin(t * 2 + seed) * 0.8;
      return { o: { dy: Math.sin(t * 2.5 + seed) * 0.8, dx: 0.8 * fire }, parts: [
        { r: [0, 0, 0.47, 0.6], sy: 1 - flap * 0.22 + fire * 0.06, pivot: 'bottom' },   // левое крыло
        { r: [0.83, 0, 1, 0.72], sy: 1 - flap * 0.22 + fire * 0.06, pivot: 'bottom' },  // правое крыло
        { r: [0, 0.58, 0.47, 1], dx: tail },                                              // хвост
        { r: [0.83, 0.7, 1, 1] },
        { r: [0.45, 0.4, 0.85, 1] },                                                      // тело
        { r: [0.45, 0, 0.85, 0.42], dx: 1.2 * fire, dy: 0.6 * fire + Math.sin(t * 1.4 + seed) * 0.4 * (1 - fire),
          rot: Math.sin(t * 0.8 + seed) * 0.05 * (1 - fire), at: [0.6, 0.4] },          // шея и голова: в покое поводит мордой
      ] };
    }
    default:
      return { o: {}, parts: [{ r: [0, 0, 1, 1] }] };
  }
}
